import jsPDF from 'jspdf';
import html2canvas from 'html2canvas';
import { DownloadedPdf } from '../types';

export interface PdfGenerationResult {
  success: boolean;
  filename: string;
  fileSizeKb: number;
  error?: string;
}

export async function generateNotePdf(
  element: HTMLElement,
  title: string,
  subject: string,
  level: string
): Promise<PdfGenerationResult> {
  const sanitizedTitle = title.replace(/[^a-zA-Z0-9_-]/g, '_').replace(/_+/g, '_');
  const filename = `${sanitizedTitle}_Notes.pdf`;

  try {
    // 1. Capture the note container with high resolution
    const canvas = await html2canvas(element, {
      scale: 2, // Retains high sharpness and crisp text
      useCORS: true,
      allowTaint: true,
      backgroundColor: '#FFFFFF',
      logging: false,
      windowWidth: element.scrollWidth,
      windowHeight: element.scrollHeight,
    });

    const imgData = canvas.toDataURL('image/jpeg', 0.95);

    // 2. Setup standard A4 dimensions in millimeters
    const pdf = new jsPDF('p', 'mm', 'a4');
    const pageWidth = pdf.internal.pageSize.getWidth(); // 210mm
    const pageHeight = pdf.internal.pageSize.getHeight(); // 297mm

    const marginX = 10;
    const marginY = 15;
    const contentWidth = pageWidth - marginX * 2; // 190mm

    const imgWidth = contentWidth;
    const imgHeight = (canvas.height * imgWidth) / canvas.width;

    let heightLeft = imgHeight;
    let position = marginY;
    let pageCount = 1;

    // First page
    pdf.addImage(imgData, 'JPEG', marginX, position, imgWidth, imgHeight);
    heightLeft -= pageHeight - marginY * 2;

    // Additional pages if the note is long
    while (heightLeft > 0) {
      position = heightLeft - imgHeight + marginY;
      pdf.addPage();
      pageCount++;
      pdf.addImage(imgData, 'JPEG', marginX, position, imgWidth, imgHeight);
      heightLeft -= pageHeight - marginY * 2;
    }

    // Add running header & footer with page numbering across all pages
    const totalPages = pageCount;
    for (let i = 1; i <= totalPages; i++) {
      pdf.setPage(i);
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(8);
      pdf.setTextColor(120, 113, 108);

      // Top running header
      pdf.text(
        `LearnGenie • ${subject} (${level} Level) • ${title.slice(0, 50)}`,
        marginX,
        8
      );
      pdf.setDrawColor(230, 225, 218);
      pdf.setLineWidth(0.3);
      pdf.line(marginX, 10, pageWidth - marginX, 10);

      // Bottom footer
      pdf.line(marginX, pageHeight - 9, pageWidth - marginX, pageHeight - 9);
      pdf.text(
        `Generated by LearnGenie Offline Assistant • Available for Offline Reading`,
        marginX,
        pageHeight - 5
      );
      pdf.text(
        `Page ${i} of ${totalPages}`,
        pageWidth - marginX - 18,
        pageHeight - 5
      );
    }

    // 3. Initiate browser download
    pdf.save(filename);

    const pdfBlob = pdf.output('blob');
    const fileSizeKb = Math.round(pdfBlob.size / 1024);

    // 4. Save metadata to local offline cache
    saveDownloadedPdfMetadata({
      id: `pdf-${Date.now()}`,
      title,
      subject,
      filename,
      downloadedAt: Date.now(),
      fileSizeKb,
    });

    return {
      success: true,
      filename,
      fileSizeKb,
    };
  } catch (err: any) {
    console.error('PDF generation failed:', err);
    return {
      success: false,
      filename,
      fileSizeKb: 0,
      error: err?.message || 'Failed to render PDF canvas',
    };
  }
}

export function getDownloadedPdfs(): DownloadedPdf[] {
  if (typeof window === 'undefined') return [];
  const stored = localStorage.getItem('learngenie_downloaded_pdfs_v1');
  if (stored) {
    try {
      return JSON.parse(stored);
    } catch (e) {
      return [];
    }
  }
  return [];
}

export function saveDownloadedPdfMetadata(item: DownloadedPdf): void {
  if (typeof window === 'undefined') return;
  const current = getDownloadedPdfs();
  const updated = [item, ...current.filter((p) => p.filename !== item.filename)].slice(0, 30);
  localStorage.setItem('learngenie_downloaded_pdfs_v1', JSON.stringify(updated));
}
